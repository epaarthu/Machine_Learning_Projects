# Import libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

print("1. Loading SMS Spam Collection dataset...")
url = "https://raw.githubusercontent.com/justmarkham/pycon-2016-tutorial/master/data/sms.tsv"
df = pd.read_csv(url, sep="\t", header=None, names=["label", "message"])

# Convert string labels ('ham' / 'spam') into numbers (0 for ham, 1 for spam)
df["y"] = (df["label"] == "spam").astype(int)

print(f"Dataset Shape: {df.shape}")
display(df.head())

print("2. Exploring class distribution...")
print(df["label"].value_counts())

# Plot distribution
plt.figure(figsize=(5, 3))
sns.countplot(x='label', data=df, palette='Set2')
plt.title("Distribution of Ham vs Spam Messages")
plt.xlabel("Message Type")
plt.ylabel("Count")
plt.show()

from sklearn.model_selection import train_test_split

print("3. Splitting data into training and testing sets...")
X_train, X_test, y_train, y_test = train_test_split(
    df["message"], df["y"], test_size=0.2, random_state=42, stratify=df["y"]
)

print(f"Training samples: {X_train.shape[0]}")
print(f"Testing samples: {X_test.shape[0]}")

from sklearn.pipeline import Pipeline
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB

print("4. Building and training the NLP pipeline...")

# Create pipeline combining text vectorization and Naive Bayes classifier
model = Pipeline([
    ("tfidf", TfidfVectorizer(lowercase=True, stop_words="english", ngram_range=(1, 2))),
    ("clf", MultinomialNB())
])

# Train the model on training data
model.fit(X_train, y_train)

print("Model trained successfully!")

from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

print("5. Evaluating predictions and calculating percentage accuracy...\n")
preds = model.predict(X_test)

# Calculate accuracy percentage
accuracy = accuracy_score(y_test, preds) * 100

print(f"========================================")
print(f"🎯 Spam Classifier Model Accuracy: {accuracy:.2f}%")
print(f"========================================\n")

# Detailed metrics report
print("Classification Report:")
print(classification_report(y_test, preds, target_names=["ham (legit)", "spam"]))

plt.figure(figsize=(5, 4))
sns.heatmap(confusion_matrix(y_test, preds), annot=True, fmt='d', cmap='Blues',
            xticklabels=["Legit (Ham)", "Spam"],
            yticklabels=["Legit (Ham)", "Spam"])
plt.xlabel('Predicted Label')
plt.ylabel('True Label')
plt.title('Spam Classifier Confusion Matrix')
plt.show()

