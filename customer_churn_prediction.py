from xgboost import XGBClassifier
from sklearn.metrics import accuracy_score, classification_report, roc_auc_score

# 1. Calculate scale_pos_weight to handle the imbalanced churn data
# Ratio of non-churned (0) to churned (1) customers
negative_count = (y_train == 0).sum()
positive_count = (y_train == 1).sum()
weight_ratio = negative_count / positive_count

print(f"Calculated scale_pos_weight ratio: {weight_ratio:.2f}")

# 2. Train an optimized XGBoost model with tuning parameters
print("\nTraining Optimized XGBoost Model...")
boosted_xgb = XGBClassifier(
    n_estimators=150,          # More trees for deeper learning
    max_depth=4,               # Shallower trees to prevent overfitting
    learning_rate=0.05,        # Slower learning rate for better stability
    scale_pos_weight=weight_ratio, # Boosts attention on churned customers
    random_state=42,
    eval_metric='logloss'
)

boosted_xgb.fit(X_train, y_train)

# 3. Evaluate the new boosted model
y_pred_boosted = boosted_xgb.predict(X_test)
y_prob_boosted = boosted_xgb.predict_proba(X_test)[:, 1]

new_accuracy = accuracy_score(y_test, y_pred_boosted) * 100
new_roc_auc = roc_auc_score(y_test, y_prob_boosted)

print(f"========================================")
print(f" Boosted Model Accuracy: {new_accuracy:.2f}%")
print(f" Boosted ROC-AUC Score:  {new_roc_auc:.4f}")
print(f"========================================\n")

print("Updated Classification Report:")
print(classification_report(y_test, y_pred_boosted, target_names=["Stayed (0)", "Churned (1)"]))